#!/usr/bin/env python3
"""Generate the firmware signal registry from contracts/signals.json.

    python3 tools/gen_signals.py           # write main/app_obd_dsp/signal_registry.{h,c}
    python3 tools/gen_signals.py --check   # fail if the committed files are stale

Only statically allocated entries (obd.*, sys.*) are emitted; veh.* slots are
assigned at profile load time by signal_store.
"""

import argparse
import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(REPO, 'contracts', 'signals.json')
OUT_H = os.path.join(REPO, 'main', 'app_obd_dsp', 'signal_registry.h')
OUT_C = os.path.join(REPO, 'main', 'app_obd_dsp', 'signal_registry.c')

OPS = {'identity': 'SIG_DLV_IDENTITY', 'mul': 'SIG_DLV_MUL', 'div': 'SIG_DLV_DIV'}
ROUNDS = {None: 'SIG_RND_EXACT', 'exact': 'SIG_RND_EXACT', 'half_up': 'SIG_RND_HALF_UP',
          'floor': 'SIG_RND_FLOOR'}

HEADER = '/* GENERATED by tools/gen_signals.py from contracts/signals.json - do not edit. */\n'


def enum_name(key):
    return 'SIG_' + re.sub(r'[^A-Za-z0-9]', '_', key).upper()


def c_str(s):
    return '"%s"' % s.replace('\\', '\\\\').replace('"', '\\"')


def c_num(v):
    return repr(float(v))


def generate(reg):
    sigs = [s for s in reg['signals'] if s['key'].split('.')[0] in ('obd', 'sys')]
    obd = [s for s in sigs if s['key'].startswith('obd.')]
    sysn = [s for s in sigs if s['key'].startswith('sys.')]
    order = obd + sysn

    h = [HEADER, '#pragma once\n', '#include <stddef.h>\n#include <stdint.h>\n\n',
         '#ifdef __cplusplus\nextern "C" {\n#endif\n\n',
         '#define SIG_REGISTRY_VERSION %d\n\n' % reg['registry_version'],
         '/* Slot index of every static signal (signal_store slot = enum value). */\n',
         'enum {\n']
    for i, s in enumerate(order):
        h.append('    %-28s = %2d,  /* %s %s */\n' % (enum_name(s['key']), i, s['id'], s['key']))
    h.append('    SIG_STD_COUNT = %d\n};\n\n' % len(order))
    h.append('#define SIG_OBD_FIRST 0\n#define SIG_OBD_COUNT %d\n' % len(obd))
    h.append('#define SIG_SYS_FIRST %d\n#define SIG_SYS_COUNT %d\n\n' % (len(obd), len(sysn)))
    h.append('typedef enum { SIG_DLV_IDENTITY = 0, SIG_DLV_MUL, SIG_DLV_DIV } sig_dlv_op_t;\n')
    h.append('typedef enum { SIG_RND_EXACT = 0, SIG_RND_HALF_UP, SIG_RND_FLOOR } sig_round_t;\n\n')
    h.append('/* Profile unit -> internal factor: internal = R(rpn_result * factor). */\n')
    h.append('typedef struct {\n    const char *unit;\n    double      factor;\n} sig_unit_t;\n\n')
    h.append('typedef struct {\n'
             '    uint16_t          num_id;      /* registry id (0x0001...) */\n'
             '    const char       *key;         /* "obd.rpm" */\n'
             '    int32_t           scale;       /* internal units per engineering unit */\n'
             '    int32_t           min;         /* plausibility range, internal units */\n'
             '    int32_t           max;\n'
             '    uint32_t          stale_ms;    /* 0 = never stale */\n'
             '    uint8_t           dlv_op;      /* sig_dlv_op_t */\n'
             '    uint8_t           dlv_round;   /* sig_round_t */\n'
             '    int8_t            editor_index;/* editor DATA_SOURCES index, -1 = none */\n'
             '    uint8_t           n_units;     /* units[0] is the profile default */\n'
             '    double            dlv_by;\n'
             '    const sig_unit_t *units;\n'
             '} sig_def_t;\n\n')
    h.append('extern const sig_def_t sig_registry[SIG_STD_COUNT];\n\n')
    h.append('/* Numeric IDs are independent of slot order; unknown static IDs return -1. */\n')
    h.append('static inline int sig_registry_slot_by_id(uint16_t num_id)\n{\n')
    # Coalesce only proven adjacent IDs with adjacent slots. Reordering or holes
    # remain exact; no runtime table or hard-coded current registry layout.
    indexed = sorted((int(s['id'], 0), slot, s) for slot, s in enumerate(order))
    groups = []
    for item in indexed:
        if groups and item[0] == groups[-1][-1][0] + 1 and item[1] == groups[-1][-1][1] + 1:
            groups[-1].append(item)
        else:
            groups.append([item])
    for group in groups:
        first_id, _, first_signal = group[0]
        slot_name = enum_name(first_signal['key'])
        if len(group) == 1:
            h.append('    if (num_id == 0x%04X) return %s;\n' % (first_id, slot_name))
        else:
            h.append('    if (num_id >= 0x%04X && num_id <= 0x%04X)\n' % (first_id, group[-1][0]))
            h.append('        return %s + (int)(num_id - 0x%04X);\n' % (slot_name, first_id))
    h.append('    return -1;\n}\n\n')
    h.append('#ifdef __cplusplus\n}\n#endif\n')

    c = [HEADER, '#include "signal_registry.h"\n\n']
    for s in order:
        units = s.get('profile_units')
        if not units:
            continue
        dflt = s.get('profile_unit_default')
        items = sorted(units.items(), key=lambda kv: (kv[0] != dflt,))
        c.append('static const sig_unit_t k_units_%s[] = {' % enum_name(s['key']).lower())
        c.append(', '.join('{%s, %s}' % (c_str(u), c_num(f)) for u, f in items))
        c.append('};\n')
    c.append('\nconst sig_def_t sig_registry[SIG_STD_COUNT] = {\n')
    for s in order:
        it = s['internal']
        d = s['delivery']
        units = s.get('profile_units')
        uname = 'k_units_%s' % enum_name(s['key']).lower() if units else 'NULL'
        ed = s.get('editor')
        c.append('    [%s] = {%s, %s, %d, %d, %d, %d, %s, %s, %d, %d, %s, %s},\n' % (
            enum_name(s['key']), s['id'], c_str(s['key']), int(it['scale']), int(it['min']),
            int(it['max']), int(s.get('stale_ms') or 0), OPS[d['op']], ROUNDS[d.get('round')],
            ed['index'] if ed else -1, len(units) if units else 0, c_num(d.get('by', 1)), uname))
    c.append('};\n')
    return ''.join(h), ''.join(c)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    with open(SRC, encoding='utf-8') as f:
        reg = json.load(f)
    out_h, out_c = generate(reg)
    stale = []
    for path, text in ((OUT_H, out_h), (OUT_C, out_c)):
        cur = open(path, encoding='utf-8').read() if os.path.exists(path) else None
        if cur == text:
            continue
        if args.check:
            stale.append(os.path.relpath(path, REPO))
        else:
            with open(path, 'w', encoding='utf-8') as f:
                f.write(text)
            print('wrote', os.path.relpath(path, REPO))
    if stale:
        print('stale (run tools/gen_signals.py):', ', '.join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
