#!/usr/bin/env python3
"""Generate main/vehicle/vp_builtin_generic.c from vehicles/catalog/obd2.generic.vehicle.json.

Usage:
    python3 tools/vehicles/gen_builtin.py [--blobgen PATH] [--check]

  --blobgen PATH   compiled vp_blobgen (test/host/vehicle). Default:
                   build/host/vehicle/vp_blobgen
  --check          do not write; exit 1 if vp_builtin_generic.c is not what
                   would be generated (CI / pre-commit)

vp_blobgen compiles with the firmware configuration (vp_validate_default_cfg(),
i.e. the generated signal registry), so the blob is byte-identical to what the
device would produce from the same JSON. Build it with:

    cmake -S test/host/vehicle -B build/host/vehicle -G Ninja
    cmake --build build/host/vehicle --target vp_blobgen

The script finds the repo root from its own location, so it can be run from
any directory.
"""

import argparse
import json
import os
import struct
import subprocess
import sys
import tempfile

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(os.path.dirname(SCRIPT_DIR))

PROFILE_JSON = os.path.join(REPO_ROOT, "vehicles", "catalog", "obd2.generic.vehicle.json")
OUT_C = os.path.join(REPO_ROOT, "main", "vehicle", "vp_builtin_generic.c")

HEADER = """\
/* vp_builtin_generic.c - GENERATED by tools/vehicles/gen_builtin.py from
 * vehicles/catalog/obd2.generic.vehicle.json - do not edit.
 *
 * Regenerate:  python3 tools/vehicles/gen_builtin.py
 * Verify:      python3 tools/vehicles/gen_builtin.py --check
 */
#include "vp_builtin.h"
"""


def die(msg):
    print("gen_builtin: error: " + msg, file=sys.stderr)
    sys.exit(2)


def compile_blob(blobgen, profile):
    """Run vp_blobgen and return the compiled blob bytes."""
    fd, tmp = tempfile.mkstemp(suffix=".bin")
    os.close(fd)
    try:
        r = subprocess.run([blobgen, profile, tmp], capture_output=True, text=True)
        if r.returncode != 0:
            die("vp_blobgen failed:\n" + r.stdout + r.stderr)
        with open(tmp, "rb") as f:
            return f.read()
    finally:
        try:
            os.unlink(tmp)
        except OSError:
            pass


def minify_json(path):
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    return json.dumps(data, separators=(",", ":"), ensure_ascii=True)


def c_string_lines(text, width=96, indent="    "):
    """Split text into C string literal lines (ASCII; escapes \\ and ")."""
    out, cur = [], ""
    for ch in text:
        esc = "\\\\" if ch == "\\" else '\\"' if ch == '"' else ch
        if len(cur) + len(esc) > width:
            out.append(indent + '"' + cur + '"')
            cur = ""
        cur += esc
    if cur or not out:
        out.append(indent + '"' + cur + '"')
    return "\n".join(out)


def u32_lines(blob, cols=6, indent="    "):
    words = struct.unpack("<%dI" % (len(blob) // 4), blob)
    rows = []
    for i in range(0, len(words), cols):
        rows.append(indent + ", ".join("0x%08Xu" % w for w in words[i:i + cols]) + ",")
    return "\n".join(rows)


def render(blob, text):
    return (HEADER + "\n"
            "/* Compiled vp_profile_t, %d bytes. */\n"
            "const uint32_t vp_builtin_generic_blob[] = {\n"
            "%s\n"
            "};\n"
            "const size_t vp_builtin_generic_blob_size = sizeof(vp_builtin_generic_blob);\n"
            "\n"
            "/* Minified source JSON, %d bytes. */\n"
            "static const char s_json[] =\n"
            "%s;\n"
            "const char *const vp_builtin_generic_json = s_json;\n"
            "const size_t vp_builtin_generic_json_len = sizeof(s_json) - 1;\n"
            % (len(blob), u32_lines(blob), len(text), c_string_lines(text)))


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--blobgen", default=os.path.join(REPO_ROOT, "build", "host", "vehicle", "vp_blobgen"),
                    help="path to the compiled vp_blobgen binary")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the generated file is stale instead of writing it")
    args = ap.parse_args()

    if not os.path.isfile(args.blobgen):
        die("vp_blobgen not found at %s; build it first:\n"
            "  cmake -S test/host/vehicle -B build/host/vehicle -G Ninja\n"
            "  cmake --build build/host/vehicle --target vp_blobgen" % args.blobgen)
    if not os.path.isfile(PROFILE_JSON):
        die("profile not found: " + PROFILE_JSON)

    blob = compile_blob(args.blobgen, PROFILE_JSON)
    if not blob or len(blob) % 4:
        die("blob size %d is not a positive multiple of 4" % len(blob))
    out = render(blob, minify_json(PROFILE_JSON))
    rel = os.path.relpath(OUT_C, REPO_ROOT)

    if args.check:
        try:
            with open(OUT_C, encoding="utf-8") as f:
                cur = f.read()
        except OSError:
            cur = None
        if cur != out:
            print("gen_builtin: %s is stale; run python3 tools/vehicles/gen_builtin.py" % rel,
                  file=sys.stderr)
            sys.exit(1)
        print("gen_builtin: %s is up to date (%d blob bytes)" % (rel, len(blob)))
        return

    with open(OUT_C, "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
    print("gen_builtin: wrote %s (%d blob bytes)" % (rel, len(blob)))


if __name__ == "__main__":
    main()
